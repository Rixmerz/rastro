type Rule = { json: string } | { input: string } | { regex: string; from: 'body' | 'url' | 'location' } | { query: string };
interface Part { name: string; value?: string; file?: string; filename?: string; contentType?: string }
interface Paginate { query?: string; next: { json: string } | { step: number } | { url: string }; items: string; maxPages: number }
interface Req {
  id: string;
  method: string;
  url: string;
  query?: { name: string; value: string }[];
  headers?: Record<string, string>;
  form?: { name: string; value: string }[];
  json?: unknown;
  multipart?: Part[];
  raw?: string;
  expect?: string;
  xhr?: boolean;
  extract?: Record<string, Rule>;
  paginate?: Paginate;
}
interface Output { as: string; request: string; json?: string; fields?: Record<string, string> }
interface Recipe { params: string[]; requests: Req[]; outputs: Output[] }
interface Cookie { name: string; value: string; domain: string; hostOnly: boolean; path: string; secure: boolean; expires: number }

const VAR = /\\{\\{\\s*(cookie:[^}\\s]+|[A-Za-z_][A-Za-z0-9_]*)(\\|number)?\\s*\\}\\}/g;

function fill(template: string, resolve: (name: string) => string | undefined, encode: (v: string) => string = (v) => v): string {
  return template.replace(VAR, (_m, name: string) => {
    const value = resolve(name);
    if (value === undefined) throw new Error('no value for {{' + name + '}}');
    return encode(value);
  });
}

function fillDeep(value: unknown, resolve: (name: string) => string | undefined): unknown {
  if (typeof value === 'string') {
    const whole = /^\\{\\{\\s*([A-Za-z_][A-Za-z0-9_]*)\\|number\\s*\\}\\}$/.exec(value);
    if (whole) return Number(fill('{{' + whole[1] + '}}', resolve));
    return fill(value, resolve);
  }
  if (Array.isArray(value)) return value.map((v) => fillDeep(v, resolve));
  if (value !== null && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, fillDeep(v, resolve)]));
  return value;
}

function isWrite(method: string): boolean {
  return !['GET', 'HEAD', 'OPTIONS'].includes(method.toUpperCase());
}

function selectJson(node: unknown, path: string): unknown {
  const tokens = path.trim() === '' ? [] : (path.match(/[^.[\\]]+|\\[\\d+\\]|\\[\\*\\]/g) ?? []);
  const step = (n: unknown, rest: string[]): unknown => {
    if (rest.length === 0) return n;
    if (typeof n === 'string') {
      try {
        return step(JSON.parse(n), rest);
      } catch {
        return undefined;
      }
    }
    const [head, ...tail] = rest as [string, ...string[]];
    if (head === '[*]') return Array.isArray(n) ? n.map((el) => step(el, tail)).filter((v) => v !== undefined) : undefined;
    if (n === null || typeof n !== 'object') return undefined;
    if (head.startsWith('[')) return Array.isArray(n) ? step(n[Number(head.slice(1, -1))], tail) : undefined;
    return step((n as Record<string, unknown>)[head], tail);
  };
  return step(node, tokens);
}

function project(value: unknown, fields: Record<string, string>): unknown {
  const one = (el: unknown) => Object.fromEntries(Object.entries(fields).map(([name, path]) => [name, selectJson(el, path) ?? null]));
  return Array.isArray(value) ? value.map(one) : one(value);
}

function withItems(root: unknown, path: string, items: unknown[]): unknown {
  const tokens = path.match(/[^.[\\]]+|\\[\\d+\\]/g) ?? [];
  const set = (node: unknown, i: number): unknown => {
    if (i === tokens.length) return items;
    const token = tokens[i]!;
    if (token.startsWith('[')) {
      const copy = Array.isArray(node) ? [...node] : [];
      copy[Number(token.slice(1, -1))] = set(copy[Number(token.slice(1, -1))], i + 1);
      return copy;
    }
    const copy: Record<string, unknown> = node !== null && typeof node === 'object' && !Array.isArray(node) ? { ...(node as Record<string, unknown>) } : {};
    copy[token] = set(copy[token], i + 1);
    return copy;
  };
  return set(root, 0);
}

function decodeEntities(text: string): string {
  return text
    .replace(/&quot;/g, '"')
    .replace(/&#0*39;|&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#(\\d+);/g, (_m, n: string) => String.fromCodePoint(Number(n)))
    .replace(/&amp;/g, '&');
}

function inputValue(html: string, name: string): string | undefined {
  for (const tag of html.match(/<input\\b[^>]*>/gi) ?? []) {
    const attrs: Record<string, string> = {};
    for (const m of tag.matchAll(/([^\\s=/>]+)\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s>]+))/g)) {
      attrs[m[1]!.toLowerCase()] = decodeEntities(m[2] ?? m[3] ?? m[4] ?? '');
    }
    if (attrs['name'] === name) return attrs['value'];
  }
  return undefined;
}

function applyRule(rule: Rule, res: { body: string; url: string; location?: string }): string | undefined {
  if ('json' in rule) {
    try {
      const value = selectJson(JSON.parse(res.body), rule.json);
      return typeof value === 'string' || typeof value === 'number' ? String(value) : undefined;
    } catch {
      return undefined;
    }
  }
  if ('input' in rule) return inputValue(res.body, rule.input);
  if ('query' in rule) return new URL(res.url).searchParams.get(rule.query) ?? undefined;
  const text = rule.from === 'body' ? res.body : rule.from === 'url' ? res.url : (res.location ?? '');
  return new RegExp(rule.regex).exec(text)?.[1];
}

function matchesPattern(pattern: string, r: { method: string; url: string; status: number }): boolean {
  const parts = pattern.trim().split(/\\s+/);
  if (parts.length !== 3) return false;
  const [method, path, status] = parts as [string, string, string];
  if (method.toUpperCase() !== r.method.toUpperCase()) return false;
  const u = new URL(r.url);
  const target = path.includes('?') ? u.pathname + u.search : u.pathname;
  const glob = new RegExp('^' + path.replace(/[.+?^\${}()|[\\]\\\\]/g, '\\\\$&').replace(/\\*/g, '.*') + '$');
  if (path.includes('*') ? !glob.test(target) : target !== path) return false;
  return /^\\d{3}$/.test(status) ? r.status === Number(status) : String(r.status)[0] === status[0];
}

class Jar {
  cookies: Cookie[] = [];

  private static matches(host: string, c: Cookie): boolean {
    return c.hostOnly ? host === c.domain : host === c.domain || host.endsWith('.' + c.domain);
  }

  private static pathMatches(path: string, cookiePath: string): boolean {
    if (path === cookiePath) return true;
    return path.startsWith(cookiePath) && (cookiePath.endsWith('/') || path[cookiePath.length] === '/');
  }

  private live(): Cookie[] {
    const now = Date.now() / 1000;
    this.cookies = this.cookies.filter((c) => c.expires === -1 || c.expires > now);
    return this.cookies;
  }

  header(url: string): string {
    const u = new URL(url);
    const secure = u.protocol === 'https:' || u.hostname === '127.0.0.1' || u.hostname === 'localhost';
    return this.live()
      .filter((c) => Jar.matches(u.hostname, c) && Jar.pathMatches(u.pathname, c.path) && (!c.secure || secure))
      .sort((a, b) => b.path.length - a.path.length)
      .map((c) => c.name + '=' + c.value)
      .join('; ');
  }

  get(name: string, url: string): string | undefined {
    const u = new URL(url);
    return this.live().find((c) => c.name === name && Jar.matches(u.hostname, c) && Jar.pathMatches(u.pathname, c.path))?.value;
  }

  store(url: string, lines: string[]): void {
    const u = new URL(url);
    for (const line of lines) {
      const [pair, ...attrs] = line.split(';');
      const eq = pair?.indexOf('=') ?? -1;
      if (!pair || eq <= 0) continue;
      const slash = u.pathname.lastIndexOf('/');
      const c: Cookie = { name: pair.slice(0, eq).trim(), value: pair.slice(eq + 1).trim(), domain: u.hostname, hostOnly: true, path: slash > 0 ? u.pathname.slice(0, slash) : '/', secure: false, expires: -1 };
      for (const attr of attrs) {
        const [rawKey, ...rest] = attr.split('=');
        const key = rawKey?.trim().toLowerCase();
        const value = rest.join('=').trim();
        if (key === 'domain' && value) {
          const domain = value.replace(/^\\./, '').toLowerCase();
          if (u.hostname !== domain && !u.hostname.endsWith('.' + domain)) continue;
          c.domain = domain;
          c.hostOnly = false;
        } else if (key === 'path' && value.startsWith('/')) c.path = value;
        else if (key === 'secure') c.secure = true;
        else if (key === 'max-age' && /^-?\\d+$/.test(value)) c.expires = Number(value) <= 0 ? 0 : Math.floor(Date.now() / 1000) + Number(value);
        else if (key === 'expires' && !Number.isNaN(Date.parse(value))) c.expires = Math.floor(Date.parse(value) / 1000);
      }
      this.cookies = this.cookies.filter((o) => !(o.name === c.name && o.domain === c.domain && o.path === c.path));
      if (c.expires === -1 || c.expires > Date.now() / 1000) this.cookies.push(c);
    }
  }
}

function expandHome(path: string): string {
  return path.startsWith('~/') ? homedir() + path.slice(1) : path;
}

function seedJar(recipe: Recipe, options: Options): Jar {
  const jar = new Jar();
  const file = options.cookieFile ?? process.env.RASTRO_COOKIES;
  if (file) jar.cookies = JSON.parse(readFileSync(expandHome(file), 'utf8')) as Cookie[];
  const header = options.cookie ?? process.env.COOKIE;
  if (header) {
    const hosts = new Set(recipe.requests.map((r) => new URL(r.url.replace(/\\{\\{[^}]*\\}\\}/g, 'x')).hostname));
    for (const pair of header.split(';')) {
      const eq = pair.indexOf('=');
      if (eq <= 0) continue;
      for (const host of hosts) jar.cookies.push({ name: pair.slice(0, eq).trim(), value: pair.slice(eq + 1).trim(), domain: host, hostOnly: true, path: '/', secure: false, expires: -1 });
    }
  }
  return jar;
}

async function replay(recipe: Recipe, params: Record<string, string>, options: Options): Promise<Result> {
  const doFetch = options.fetch ?? fetch;
  const jar = seedJar(recipe, options);
  const vars: Record<string, string> = { ...params };
  const writes: Write[] = [];
  const responses: { method: string; url: string; status: number; body: string }[] = [];
  let currentUrl = '';
  let landing: string | undefined;
  let sent = 0;
  const resolve = (name: string): string | undefined => (name.startsWith('cookie:') ? jar.get(name.slice(7), currentUrl) : vars[name]);

  const send = async (method: string, url: string, headers: Headers, body: BodyInit | undefined, onFirst: (res: Response) => void) => {
    let first: Response | undefined;
    for (let hop = 0; ; hop++) {
      const cookie = jar.header(url);
      if (cookie) headers.set('cookie', cookie);
      else headers.delete('cookie');
      const init: RequestInit = { method, headers, redirect: 'manual', signal: AbortSignal.timeout(options.timeoutMs ?? 30_000) };
      if (body !== undefined) init.body = body;
      const res = await doFetch(url, init);
      jar.store(url, res.headers.getSetCookie());
      if (!first) {
        first = res;
        onFirst(res);
      }
      const location = res.headers.get('location');
      if (res.status >= 300 && res.status < 400 && location && hop < 10) {
        await res.arrayBuffer().catch(() => undefined);
        url = new URL(location, url).href;
        if (res.status === 303 || ((res.status === 301 || res.status === 302) && method !== 'GET' && method !== 'HEAD')) {
          method = 'GET';
          body = undefined;
          headers.delete('content-type');
        }
        continue;
      }
      return { first, res, url };
    }
  };

  for (const req of recipe.requests) {
    const url = new URL(fill(req.url, resolve, encodeURIComponent));
    for (const q of req.query ?? []) url.searchParams.append(q.name, fill(q.value, resolve));
    currentUrl = url.href;
    const requestUrl = currentUrl;
    const headers = new Headers();
    for (const [name, value] of Object.entries(req.headers ?? {})) headers.set(name, fill(value, resolve));
    let body: BodyInit | undefined;
    if (req.form) body = new URLSearchParams(req.form.map((f) => [f.name, fill(f.value, resolve)]));
    else if (req.json !== undefined) body = JSON.stringify(fillDeep(req.json, resolve));
    else if (req.raw !== undefined) body = fill(req.raw, resolve);
    else if (req.multipart) {
      const form = new FormData();
      for (const part of req.multipart) {
        if (part.file !== undefined) {
          const path = expandHome(fill(part.file, resolve));
          if (options.allowFile && !options.allowFile(path)) throw new ReplayError(req.id + ': file not allowed: ' + path, writes);
          form.append(part.name, new Blob([readFileSync(path)], part.contentType ? { type: part.contentType } : {}), part.filename ?? basename(path));
        } else form.append(part.name, fill(part.value ?? '', resolve));
      }
      body = form;
    }

    const out = await send(req.method, currentUrl, headers, body, (res) => {
      sent += 1;
      if (isWrite(req.method)) writes.push({ method: req.method, url: requestUrl, status: res.status });
    });
    currentUrl = out.url;
    let text = await out.res.text();
    if (!req.xhr) landing = currentUrl;
    const got = String(out.first.status)[0] + 'xx';
    if (req.expect && got !== req.expect) {
      throw new ReplayError(req.id + ' ' + req.method + ' ' + requestUrl + ' answered ' + out.first.status + ' where ' + req.expect + ' was recorded (expired session?)', writes);
    }

    if (req.paginate) {
      const p = req.paginate;
      const root = JSON.parse(text) as unknown;
      const firstItems = selectJson(root, p.items);
      if (!Array.isArray(firstItems)) throw new ReplayError(req.id + ': paginates but ' + (p.items || 'the response') + ' is not a list', writes);
      const all = [...firstItems];
      let page = root;
      let pageUrl = currentUrl;
      let lastLength = firstItems.length;
      const seen = new Set([pageUrl]);
      for (let n = 1; n < p.maxPages && lastLength > 0; n++) {
        const u = new URL(pageUrl);
        let next: string | undefined;
        if ('url' in p.next) {
          const v = selectJson(page, p.next.url);
          if (typeof v === 'string' && v !== '' && new URL(v, u).origin === u.origin) next = new URL(v, u).href;
        } else if ('json' in p.next) {
          const v = selectJson(page, p.next.json);
          if ((typeof v === 'string' || typeof v === 'number') && String(v) !== '' && u.searchParams.get(p.query!) !== String(v)) {
            u.searchParams.set(p.query!, String(v));
            next = u.href;
          }
        } else if (lastLength >= firstItems.length && Number.isFinite(Number(u.searchParams.get(p.query!) ?? NaN))) {
          u.searchParams.set(p.query!, String(Number(u.searchParams.get(p.query!)) + p.next.step));
          next = u.href;
        }
        if (next === undefined || seen.has(next)) break;
        seen.add(next);
        const res = await send('GET', next, headers, undefined, () => {
          sent += 1;
        });
        if (res.first.status < 200 || res.first.status >= 300) throw new ReplayError(req.id + ': page ' + (n + 1) + ' answered ' + res.first.status, writes);
        page = JSON.parse(await res.res.text()) as unknown;
        const items = selectJson(page, p.items);
        const list = Array.isArray(items) ? items : [];
        all.push(...list);
        lastLength = list.length;
        pageUrl = next;
      }
      if (all.length > firstItems.length) text = JSON.stringify(withItems(root, p.items, all));
    }
    responses.push({ method: req.method, url: requestUrl, status: out.first.status, body: text });

    const location = out.first.headers.get('location');
    const response = location ? { body: text, url: currentUrl, location: new URL(location, requestUrl).href } : { body: text, url: currentUrl };
    for (const [name, rule] of Object.entries(req.extract ?? {})) {
      const value = applyRule(rule, response);
      if (value === undefined) throw new ReplayError(req.id + ': could not extract ' + name + ' from the response', writes);
      vars[name] = value;
    }
  }

  const outputs: Record<string, unknown> = {};
  for (const spec of recipe.outputs) {
    const pattern = fill(spec.request, resolve);
    const match = responses.filter((r) => matchesPattern(pattern, r)).at(-1);
    let value: unknown;
    try {
      value = match ? JSON.parse(match.body) : undefined;
    } catch {
      value = undefined;
    }
    if (value !== undefined && spec.json !== undefined) value = selectJson(value, spec.json);
    if (value === undefined) throw new ReplayError('capture ' + spec.as + ': no JSON from ' + pattern + ' in the replay', writes);
    outputs[spec.as] = spec.fields ? project(value, spec.fields) : value;
  }
  return { outputs, finalUrl: landing ?? currentUrl, requestsSent: sent, writes };
}

